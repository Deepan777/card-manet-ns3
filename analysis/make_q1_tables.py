def write(name, lines):
    TAB.mkdir(parents=True, exist_ok=True)
    (TAB / name).write_text("%% generated by analysis/make_q1_tables.py -- do not edit" + NL
                            + NL.join(lines) + NL, encoding="utf-8")


def f3(x):
    return ("$%+.3f$" % x).replace("+", "{+}") if x is not None else "--"


def ci(lo, hi):
    return "[$%+.3f$, $%+.3f$]" % (lo, hi)


def sample_size_rule():
    """Cells failing the registered rule, from analyze_campaign.py's own output."""
    import re as _re
    res = {}
    import subprocess
    import sys
    for tag, f, camp in (("C1", "c1_timely_pdr.txt", "c1_outage"), ("C4", "c4_timely_pdr.txt", "c4_scaling"),
                         ("S8", "stage8_timely_pdr.txt", "stage8_campaign")):
        path = ROOT / "analysis_out" / f
        if not path.exists():
            # regenerate from the run records with the campaign analysis that defines the rule
            out = subprocess.run([sys.executable, str(ROOT / "analysis" / "analyze_campaign.py"),
                                  "--campaign", camp, "--metric", "timely_pdr"],
                                 capture_output=True, text=True, cwd=str(ROOT)).stdout
            path.parent.mkdir(exist_ok=True)
            path.write_text(out)
        lines = [l for l in path.read_text(errors="replace").splitlines()
                 if _re.search(r" (None|10|20|30)$", l)]
        res[tag] = {"cells": len(lines), "fail": sum(1 for l in lines if l.endswith(" None"))}
    return res


