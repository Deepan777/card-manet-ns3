def main():
    J = {}
    camps = {"C1": load("c1_outage"), "C4": load("c4_scaling"), "S8": load("stage8_campaign")}

    # ---------- ordering: mean paired difference vs stock over conditions ----------
    ordering = {}
    for tag, rows in camps.items():
        conds = conditions(rows)
        per = {p: [] for p in POLICIES}
        full = 0
        for c in conds:
            m = [mean_of(rows, p, c) for p in POLICIES]
            if all(x is not None for x in m) and all(m[i] > m[i + 1] for i in range(3)):
                full += 1
            for p in POLICIES:
                d = paired(rows, p, REF, c)
                if d:
                    per[p].append(st.mean(d))
        ordering[tag] = {"conditions": len(conds), "full_order": full,
                         "rrep_gt_tb": sum(1 for c in conds
                                           if mean_of(rows, "RREP-RESET", c) > mean_of(rows, "TIME-BUCKET", c)),
                         **{p: {"mean": st.mean(v), "min": min(v), "max": max(v)} for p, v in per.items()}}
    J["ordering"] = ordering
    L = [B + "begin{tabular}{@{}lccc@{}}", B + "toprule",
         "Renewal policy & Bottleneck (%d) & Scaling (%d) & Mobility (%d) " % tuple(
             ordering[k]["conditions"] for k in ("C1", "C4", "S8")) + B + B, B + "midrule"]
    for p in POLICIES:
        cells = []
        for tag in ("C1", "C4", "S8"):
            o = ordering[tag][p]
            cells.append("%s {\\scriptsize[%s, %s]}" % (f3(o["mean"]), f3(o["min"]), f3(o["max"])))
        L.append("%s & %s %s" % (LABEL[p], " & ".join(cells), B + B))
    L += [B + "midrule",
          "Conditions with the full order & %d / %d & %d / %d & %d / %d %s" % (
              ordering["C1"]["full_order"], ordering["C1"]["conditions"],
              ordering["C4"]["full_order"], ordering["C4"]["conditions"],
              ordering["S8"]["full_order"], ordering["S8"]["conditions"], B + B),
          B + "bottomrule", B + "end{tabular}"]
    write("tab_ordering.tex", L)

    # ---------- absolute timely PDR and control bytes ----------
    ab = {}
    for tag, rows in camps.items():
        for alg in [REF] + POLICIES:
            t = [val(kv, "timely") for (a, c, s), kv in rows.items() if a == alg]
            b = [val(kv, "bytes_per_pkt") for (a, c, s), kv in rows.items() if a == alg]
            ab[(tag, alg)] = (st.mean(t), st.mean(b), len(t))
    J["absolute"] = {"%s %s" % k: {"timely": v[0], "bytes_per_pkt": v[1], "runs": v[2]} for k, v in ab.items()}
    L = [B + "begin{tabular}{@{}lcccccc@{}}", B + "toprule",
         " & " + B + "multicolumn{2}{c}{Bottleneck} & " + B + "multicolumn{2}{c}{Scaling} & "
         + B + "multicolumn{2}{c}{Mobility} " + B + B,
         B + "cmidrule(lr){2-3}" + B + "cmidrule(lr){4-5}" + B + "cmidrule(lr){6-7}",
         "Arm & PDR$_{" + B + "mathrm{t}}$ & B/pkt & PDR$_{" + B + "mathrm{t}}$ & B/pkt & PDR$_{"
         + B + "mathrm{t}}$ & B/pkt " + B + B, B + "midrule"]
    for alg in [REF] + POLICIES:
        cells = []
        for tag in ("C1", "C4", "S8"):
            t, b, _ = ab[(tag, alg)]
            cells += ["%.3f" % t, "%.1f" % b]
        L.append("%s & %s %s" % (LABEL[alg], " & ".join(cells), B + B))
    L += [B + "bottomrule", B + "end{tabular}"]
    write("tab_absolute.tex", L)

    # ---------- principal results by regime (main text) ----------
    L = [B + "begin{tabular}{@{}l" + "rrr" * 3 + "@{}}", B + "toprule",
         " & " + " & ".join(B + "multicolumn{3}{c}{%s (%d cond.)}" % (nm, ordering[tg]["conditions"])
                             for tg, nm in (("C1", "Bottleneck"), ("C4", "Scaling"), ("S8", "Mobility")))
         + " " + B + B,
         B + "cmidrule(lr){2-4}" + B + "cmidrule(lr){5-7}" + B + "cmidrule(lr){8-10}",
         "Policy" + (" & PDR$_{" + B + "mathrm{t}}$ & $" + B + "Delta$ & B/pkt") * 3 + " " + B + B,
         B + "midrule"]
    for alg in [REF] + POLICIES:
        cells = []
        for tag in ("C1", "C4", "S8"):
            t, b, _ = ab[(tag, alg)]
            d = "--" if alg == REF else f3(ordering[tag][alg]["mean"])
            cells += ["%.3f" % t, d, "%.1f" % b]
        L.append("%s & %s %s" % (LABEL[alg], " & ".join(cells), B + B))
    L += [B + "bottomrule", B + "end{tabular}"]
    write("tab_principal.tex", L)

    # ---------- relative changes quoted in prose ----------
    rel = {}
    for tag in ("C1", "C4", "S8"):
        st_t, st_b, _ = ab[(tag, REF)]
        for alg in POLICIES:
            t, b, _ = ab[(tag, alg)]
            rel["%s %s" % (tag, alg)] = {"timely_rel_pct": 100 * (t / st_t - 1),
                                         "bytes_rel_pct": 100 * (b / st_b - 1)}
    J["relative_vs_stock"] = rel

    # ---------- origination count vs channel bytes ----------
    fb = {}
    for tag, rows in camps.items():
        for alg in POLICIES:
            o = so = b = sb = 0.0
            for c in conditions(rows):
                for (a, cc, s), kv in rows.items():
                    if a == alg and cc == c and (REF, c, s) in rows:
                        r = rows[(REF, c, s)]
                        o += val(kv, "source_rreq_originated"); so += val(r, "source_rreq_originated")
                        b += val(kv, "ctrl_bytes_sent"); sb += val(r, "ctrl_bytes_sent")
            fb["%s %s" % (tag, alg)] = {"orig_pct": 100 * (o / so - 1), "bytes_pct": 100 * (b / sb - 1)}
    J["frequency_vs_bytes"] = fb

    # ---------- route-error messages relative to stock (paired sums) ----------
    re_ = {}
    for tag, rows in camps.items():
        for alg in POLICIES:
            per = []
            x = sx = 0.0
            for c in conditions(rows):
                a1 = sum(val(kv, "ctrl_rerr_sent") for (a, cc, s), kv in rows.items()
                         if a == alg and cc == c and (REF, c, s) in rows)
                a0 = sum(val(rows[(REF, c, s)], "ctrl_rerr_sent") for (a, cc, s) in rows
                         if a == alg and cc == c and (REF, c, s) in rows)
                per.append(100 * (a1 / a0 - 1))
                x += a1; sx += a0
            re_["%s %s" % (tag, alg)] = {"pooled_pct": 100 * (x / sx - 1), "min_pct": min(per),
                                         "max_pct": max(per)}
    J["rerr_vs_stock"] = re_
    J["evidence_lag"] = json.loads((ROOT / "analysis_out" / "evidence_lag.json").read_text())["lag"]
    J["runs"] = {"main": sum(len(r) for r in camps.values())}
    J["runs"]["all"] = J["runs"]["main"] + len(load("c1_scr2_supplement")) + len(load("stage9_ablation_sweep"))
    L = [B + "begin{tabular}{@{}lcccccc@{}}", B + "toprule",
         " & " + B + "multicolumn{2}{c}{Bottleneck} & " + B + "multicolumn{2}{c}{Scaling} & "
         + B + "multicolumn{2}{c}{Mobility} " + B + B,
         B + "cmidrule(lr){2-3}" + B + "cmidrule(lr){4-5}" + B + "cmidrule(lr){6-7}",
         "Policy & orig. & bytes & orig. & bytes & orig. & bytes " + B + B, B + "midrule"]
    for alg in POLICIES:
        cells = []
        for tag in ("C1", "C4", "S8"):
            v = fb["%s %s" % (tag, alg)]
            cells += ["$%+.1f$" % v["orig_pct"], "$%+.1f$" % v["bytes_pct"]]
        L.append("%s & %s %s" % (LABEL[alg], " & ".join(cells), B + B))
    L += [B + "bottomrule", B + "end{tabular}"]
    write("tab_frequency.tex", L)

    # ---------- mechanism: C1 per-run counters, incl. SCR-2 ----------
