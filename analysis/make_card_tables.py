"""Generate the CARD tables and prose macros from the run records (R053-R055).

Writes
  paper/tables/tab_card_main.tex        CARD against the baselines, per family
  paper/tables/tab_card_ablation.tex    which part of CARD does the work
  paper/tables/tab_card_classifier.tex  break verdicts against true geometry
  paper/tables/tab_card_search.tex      searches and relays per search, every scenario (R059)
  paper/tables/tab_card_compose.tex     preregistered CARD-CLAF composition test (R060)
  paper/tables/tab_card_fading.tex      preregistered fading supplement (R056)
  paper/tables/card_numbers.tex         one macro per number quoted in the prose
  analysis_out/card_tables.json              every number, for checking prose against tables

CARD runs come from checkpoints/card_campaign (fork_rev 7); every baseline comes
from the published campaigns at the same conditions and seeds (fork_rev 5). The
pairing is valid because rev 7 reproduces rev 5 exactly for every pre-CARD mode
and node trajectories agree across algorithms to within 4e-8 m (R055).

Run:  python analysis/make_card_tables.py
"""

